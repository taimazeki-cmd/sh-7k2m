// Explicit half-tile coordinates preserve openings and staggered supports in each silhouette.
function layer(grid) {
  return grid.trim().split('\n').flatMap(line => {
    const [row, cells] = line.trim().split(':');
    return [...cells.trim()].flatMap((cell, x) => cell === 'X' ? [{ x, y: Number(row) }] : []);
  });
}

